#!/usr/bin/env python3

import argparse
from collections import OrderedDict
import json
import os
import pathlib
import shutil
import subprocess
import sys

#
# Description
#   This function writes data to the
#   the specified file
#
# Parameters
#   path - The path to the file
#   text - The text to write
#
# Returns
#   Nothing
#
def write_file(path, text) :

    # Create directory if needed
    pathlib.Path(path).parents[0].mkdir(parents=True, exist_ok=True)

    print("-- Writing {}".format(path))

    with open(path, "w") as f :
        f.write(text)

#
# Description
#   This function appends data to the
#   the specified file
#
# Parameters
#   path - The path to the file
#   text - The text to append
#
# Returns
#   Nothing
#
def append_to_file(path, text) :

    print("-- Writing {}".format(path))

    with open(path, 'a') as file :
        file.write(text + '\n')

#
# Description
#   This function reads data from the
#   the specified file
#
# Parameters
#   path - The path to the file
#
# Returns
#   The file content
#
def read_file(path) :

    with open(path, "w") as f :
        return f.read()

#
# Description
#   This function takes a list of dependencies
#   and creates a string to be pasted into
#   the CMakeLists.txt with proper indentation
#
# Parameters
#   deps - The list of dependencies
#
# Returns
#   The string to paste
#
def make_deps_str(deps) :
        return "\n".join([f"    {dep}" for dep in deps])

#
# Description
#   This function creates an empty main.cpp
#
# Parameters
#   None
#
# Returns
#   The content of an empty main.cpp
#
def get_empty_main_content() :

    return """
#include <cstdint>

int main(int /* argc */, char ** /* argv */)
{
  return 0;
}
"""

#
# Description
#   This function creates an gtest runner main file
#
# Parameters
#   None
#
# Returns
#   The content of a gtest runner main file
#
def get_gtest_runner_cpp_content() :

    return """
#include "gtestrunner.h"

int main(int argc, char* argv[])
{
  testing::InitGoogleTest(&argc, argv);

  return RUN_ALL_TESTS();
}
"""

#
# Description
#   This function creates an gtest runner main header file
#
# Parameters
#   None
#
# Returns
#   The content of a gtest runner main header file
#
def get_gtest_runner_h_content() :

    return """
#pragma once

#if _WIN32
#  pragma warning(push)
#  pragma warning(disable:4275)
#endif

#include "gtest/gtest.h"

#if _WIN32
#  pragma warning(pop)
#endif
"""

#
# Description
#   This function creates a CMakeLists.txt for an application
#
# Parameters
#   name    - The name of the application
#   project - The name of the project
#
# Returns
#   The content of the CMakeLists.txt file
#
def get_application_cmakelists_content(name, project, pub_deps, pri_deps) :

    content = """
# =============
# == SOURCES ==
# =============

set(SRC_FILES
  src/main.cpp
)

# Logical groups
source_group(TREE ${CMAKE_CURRENT_SOURCE_DIR}/src PREFIX "src" FILES ${SRC_FILES})

# ===========
# == BUILD ==
# ===========

add_executable([[name]]
  ${SRC_FILES}
)

# Include
target_include_directories([[name]]
  PRIVATE
    $<BUILD_INTERFACE:${CMAKE_CURRENT_SOURCE_DIR}/src>
)

# Link
target_link_libraries([[name]]
  PRIVATE
[[deps]]
)

# Defines
target_compile_definitions([[name]]
  PRIVATE
)

# Feature
target_compile_features([[name]]
  PRIVATE
)

# =============
# == INSTALL ==
# =============

if(NOT APPLE)

  # Fix RPATH upon installation by replacing
  # the absolute RPATH generated by the compiler
  # to where libraries were really installed
  set_target_properties([[name]]
    PROPERTIES
        INSTALL_RPATH $ORIGIN/${RELATIVE_PATH_BIN_TO_LIB}
  )

endif()

# Install the target runtime
install(
  TARGETS [[name]]
  RUNTIME DESTINATION ${CMAKE_INSTALL_BINDIR} # For binaries and dll
          COMPONENT   [[project]]-runtime
)

# ==============
# == APPIMAGE ==
# ==============

evs_generate_manifest(
  TARGET [[name]]
)

if([[project_name_upper_underscore]]_BUILD_APPIMAGES)
  evs_make_appimage(
    TARGET [[name]]
  )
endif()
"""
    content = (
        content
            .replace("[[name]]",    name)
            .replace("[[project]]", project.lower())
            .replace("[[deps]]",    make_deps_str(pub_deps + pri_deps))
            .replace("[[project_name_upper_underscore]]", project.upper().replace("-", "_"))
    )

    return content

#
# Description
#   This function creates a CMakeLists.txt for a library
#
# Parameters
#   name    - The name of the library
#   project - The name of the project
#
# Returns
#   The content of the CMakeLists.txt file
#
def get_library_cmakelists_content(name, project, pub_deps, pri_deps) :

    content = """
# =============
# == SOURCES ==
# =============

set(PUBLIC_INCLUDE_FILES
  include/[[name]]/dummy.h
)

set(SRC_FILES
  src/dummy.cpp
)

set(CURRENT_LIB_NAME [[name_underscore]])
configure_file(
  ${PROJECT_SOURCE_DIR}/compiled_version.h.in
  ${CMAKE_CURRENT_BINARY_DIR}/[[name]]/compiled_version.h
  @ONLY
)

set(PUBLIC_GENERATED_INCLUDE_FILES
  ${CMAKE_CURRENT_BINARY_DIR}/[[name]]/compiled_version.h
)

# Logical groups
source_group(TREE ${CMAKE_CURRENT_SOURCE_DIR}/include PREFIX "public" FILES ${PUBLIC_INCLUDE_FILES})
source_group(TREE ${CMAKE_CURRENT_SOURCE_DIR}/src     PREFIX "src"    FILES ${SRC_FILES})

# ===========
# == BUILD ==
# ===========

add_library([[name]]-objects OBJECT
 ${PUBLIC_INCLUDE_FILES}
 ${SRC_FILES}
 ${PUBLIC_GENERATED_INCLUDE_FILES}
)

# Create alias
add_library(EVS::[[name]]-objects ALIAS [[name]]-objects)

# Include
target_include_directories([[name]]-objects
  PUBLIC
    $<BUILD_INTERFACE:${CMAKE_CURRENT_SOURCE_DIR}/include>
    $<BUILD_INTERFACE:${CMAKE_CURRENT_BINARY_DIR}>
    $<INSTALL_INTERFACE:${CMAKE_INSTALL_INCLUDEDIR}>

  PRIVATE
)

# Link
target_link_libraries([[name]]-objects
  PUBLIC
[[pub_deps]]
  PRIVATE
[[pri_deps]]
)

# Defines
target_compile_definitions([[name]]-objects
  PUBLIC

  PRIVATE
    # Make directives export
    -D[[name_underscore]]_EXPORTS=1
)

# Feature
target_compile_features([[name]]-objects
  PUBLIC

  PRIVATE
)

# ====================
# == CREATE LIBRARY ==
# ====================

# Now create the "real" library
file(WRITE ${CMAKE_CURRENT_BINARY_DIR}/Dummy.cpp)

# Make sure we have at least one file
add_library([[name]]
  ${CMAKE_CURRENT_BINARY_DIR}/Dummy.cpp
)

# Link with object library
target_link_libraries([[name]]
  PUBLIC
    EVS::[[name]]-objects
)

# Create alias
add_library(EVS::[[name]] ALIAS [[name]])

# ====================
# == API management ==
# ====================

include(GenerateExportHeader)

# This CMake function generates a header file (i.e. [[name]]_export.h)
# that contains all the proper 'defines' to import/export symbols
# (e.g. [[name_upper_underscore]]_EXPORT) for shared libraries. When building as static
# those macros are simply blank. This file will be by default generated
# into ${CMAKE_CURRENT_BINARY_DIR} (see target_include_directories above)
generate_export_header([[name]])

# =============
# == INSTALL ==
# =============

if(NOT APPLE)

  # Fix RPATH upon installation by replacing
  # the absolute RPATH generated by the compiler
  # by a keyword that basically says 'look for my
  # dependencies in the directory I'm currently
  # installed'.
  set_target_properties([[name]] PROPERTIES
    INSTALL_RPATH $ORIGIN
  )

endif()

# Install the target runtime
install(
  TARGETS  [[name]] [[name]]-objects
  EXPORT   [[project_name_upper_underscore]]
  RUNTIME  DESTINATION        ${CMAKE_INSTALL_BINDIR}     # For binaries and dll
           COMPONENT          [[project]]-runtime
  LIBRARY  DESTINATION        ${CMAKE_INSTALL_LIBDIR}     # For shared libraries
           COMPONENT          [[project]]-runtime
           NAMELINK_COMPONENT [[project]]-devel
  ARCHIVE  DESTINATION        ${CMAKE_INSTALL_LIBDIR}     # For static libraries
           COMPONENT          [[project]]-devel
)

# Install the public headers
install(FILES       ${PUBLIC_INCLUDE_FILES} ${PUBLIC_GENERATED_INCLUDE_FILES}
        DESTINATION ${CMAKE_INSTALL_INCLUDEDIR}/[[name]]
        COMPONENT   [[project]]-devel
)
install(FILES       ${CMAKE_CURRENT_BINARY_DIR}/[[name]]_export.h
        DESTINATION ${CMAKE_INSTALL_INCLUDEDIR}
        COMPONENT   [[project]]-devel
)

# ===========
# == TESTS ==
# ===========

if([[project_name_upper_underscore]]_BUILD_TESTS)
  add_subdirectory(tests)
endif()
"""
    content = (
        content
            .replace("[[name]]",                          name)
            .replace("[[name_underscore]]",               name.replace("-", "_"))
            .replace("[[name_upper_underscore]]",         name.upper().replace("-", "_"))
            .replace("[[project]]",                       project.lower())
            .replace("[[project_name_upper_underscore]]", project.upper().replace("-", "_"))
            .replace("[[pub_deps]]",                      make_deps_str(pub_deps))
            .replace("[[pri_deps]]",                      make_deps_str(pri_deps))
    )

    return content

#
# Description
#   This function creates a CMakeLists.txt for testing a library
#
# Parameters
#   name - The name of the library
#
# Returns
#   The content of the CMakeLists.txt file
#
def get_test_cmakelists_content(name) :

    content = """
include(GoogleTest)

# =============
# == SOURCES ==
# =============

set(SOURCES_FILES
  src/gtestrunner.cpp
  src/gtestrunner.h

)

# For Visual Studio
source_group(TREE ${CMAKE_CURRENT_SOURCE_DIR}/src PREFIX "src" FILES ${SOURCES_FILES})

# ===========
# == BUILD ==
# ===========

# Create target
add_executable([[name]]-tests
  ${SOURCES_FILES}
)

# Includes
target_include_directories([[name]]-tests
  PRIVATE
    $<BUILD_INTERFACE:${CMAKE_CURRENT_SOURCE_DIR}/include>
    $<BUILD_INTERFACE:${CMAKE_CURRENT_SOURCE_DIR}/src>
    $<BUILD_INTERFACE:${CMAKE_CURRENT_SOURCE_DIR}/../src>
)

# Link
target_link_libraries([[name]]-tests
  PRIVATE
    EVS::[[name]]-objects
    GTest::GTest
)

# Defines
target_compile_definitions([[name]]-tests
  PRIVATE
    # void import directive if library was shared as
    # we are actually linking with the object library
    -D[[name_upper_underscore]]_STATIC_DEFINE=1
)

# Add test and allow them to run in //
gtest_discover_tests([[name]]-tests
  XML_OUTPUT_DIR     ${CMAKE_BINARY_DIR}/GTestReports/
  TEST_PREFIX        [[name]]_
   DISCOVERY_TIMEOUT 120
   DISCOVERY_MODE    PRE_TEST
   WORKING_DIRECTORY $<TARGET_FILE_DIR:[[name]]>
)

# If you plan on running your unit tests with Valgrind
# it might happen that you need to add 'suppressions'
# to silence known issues. valgrind accepts suppressions
# by taking a file (--log-file=...). The variable
# MEMORYCHECK_SUPPRESSIONS_FILE is not a CMake variable
# but can be used as a convenience to accumulate suppressions
# from all the unit tests. Consequently, if you configure
# valgrind to use that file and define this variable, you will
# have the expected result.
if(MEMORYCHECK_SUPPRESSIONS_FILE)
  file(READ   valgrind_suppression.txt           CONTENT)
  file(APPEND ${MEMORYCHECK_SUPPRESSIONS_FILE} ${CONTENT})
endif()
"""

    content = (
        content
            .replace("[[name]]",                  name)
            .replace("[[name_underscore]]",       name.replace("-", "_"))
            .replace("[[name_upper_underscore]]", name.upper().replace("-", "_"))
    )

    return content

#
# Description
#   This function creates an application component
#
# Parameters
#   name      - The name of the application
#   project   - The name of the project
#   directory - The base directory
#
# Returns
#   Nothing
#
def create_application(name, project, directory, pub_deps, pri_deps) :

   # Create a src directory with an empty main.cpp
   write_file(os.path.join(directory, "src", "main.cpp"), get_empty_main_content())
   write_file(os.path.join(directory, "CMakeLists.txt"),  get_application_cmakelists_content(name, project, pub_deps, pri_deps))

#
# Description
#   This function creates library component
#
# Parameters
#   name      - The name of the library
#   project   - The name of the project
#   directory - The base directory
#
# Returns
#   Nothing
#
def create_library(name, project, directory, pub_deps, pri_deps) :

   # Create library
   write_file(os.path.join(directory, "src",           "dummy.cpp"), "")
   write_file(os.path.join(directory, "include", name, "dummy.h"),   "")
   write_file(os.path.join(directory, "CMakeLists.txt"),             get_library_cmakelists_content(name, project, pub_deps, pri_deps))

   # Create tests for library
   write_file(os.path.join(directory, "tests", "src", "gtestrunner.cpp"),   get_gtest_runner_cpp_content())
   write_file(os.path.join(directory, "tests", "src", "gtestrunner.h"),     get_gtest_runner_h_content  ())
   write_file(os.path.join(directory, "tests", "CMakeLists.txt"),           get_test_cmakelists_content(name))
   write_file(os.path.join(directory, "tests", "valgrind_suppression.txt"), "")

#
# Description
#   This function adds the new component to the solution
#
# Parameters
#   name          - The name of the project
#   solution_file - The path to the solution file
#
# Returns
#   Nothing
#
def add_component_to_solution(name, solution_file) :
    append_to_file(solution_file, f"add_subdirectory(sources/{name})")

#
# Description
#   This function adds the given relative path to code
#   coverage exclusion file
#
# Parameters
#   path    - The path to the coverage file
#   content - The content to add
#
# Returns
#   Nothing
#
def add_coverage_exclusion(path, content) :
    append_to_file(path, content)

#
# Description
#   This is the entry point of the script
#
# Parameters
#   argv - The arguments passed on the command line
#
# Returns
#   0 - The operation was successful
#  !0 - The operation failed
#
def main(argv):

    project_name = "onbings-vista"
    current_dir  = str(pathlib.Path(__file__).parent.resolve())

    parser = argparse.ArgumentParser(description=f"This script add a library or an application to {project_name}")

    # Mandatory arguments
    requiredArguments = parser.add_argument_group('Mandatory arguments')

    #requiredArguments.add_argument("--name", dest="name", help="The component name (e.g evs-mylib)", required=True)

    # Optional arguments
    parser.add_argument("--lib",          dest="lib",      help="The component will be a library")
    parser.add_argument("--app",          dest="app",      help="The component will be an application")
    parser.add_argument("--public-deps",  dest="pub_deps", help="The comma separated list of public dependencies",  type=lambda s: [item for item in s.split(',')])
    parser.add_argument("--private-deps", dest="pri_deps", help="The comma separated list of private dependencies", type=lambda s: [item for item in s.split(',')])

    args = parser.parse_args(argv)

    is_app   = args.app
    is_lib   = args.lib
    name     = args.app if args.app else args.lib
    pub_deps = args.pub_deps if args.pub_deps else []
    pri_deps = args.pri_deps if args.pri_deps else []
    rel_path = os.path.join("code", "sources", name)
    out_dir  = os.path.join(current_dir, rel_path)

    # Check if output directory does not yet exists
    if os.path.exists(out_dir) :
        raise ValueError("The output directory already exists. Clear it before if you want to override it : {}".format(out_dir))

    # Check type
    if (not is_lib and not is_app) or (is_lib and is_app) :
        raise ValueError("The project should either be a library (--lib) or an application (--app)")

    #====================
    #== Create project ==
    #====================

    print("Creating {} ({}) for project {} at {}".format(name, "application" if is_app else "library", project_name, out_dir))

    if is_lib :
        create_library    (name, project_name, out_dir, pub_deps, pri_deps)
    else :
        create_application(name, project_name, out_dir, pub_deps, pri_deps)
        add_coverage_exclusion(os.path.join(current_dir, "coverage.exclusion"), rel_path)

    add_component_to_solution(name, os.path.join(current_dir, "code", "CMakeLists.txt"))

    return 0

#
# Description
#   The script main wrapper
#
if __name__ == "__main__":
    try :
      sys.exit(main(sys.argv[1:]))
    except Exception as e :
      print(e)
      sys.exit(1)
